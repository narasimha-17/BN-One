import { chromium } from 'playwright'
const sp = process.argv[2]
const b = await chromium.launch()
const errs = []
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
p.on('pageerror', (e) => errs.push(e.message))
await p.goto('http://localhost:4173/resources', { waitUntil: 'networkidle' })
await p.addStyleTag({ content: 'html{scroll-behavior:auto!important}' })
await p.waitForTimeout(3500)
await p.getByText('Reject optional').first().click().catch(() => {})
const H = await p.evaluate(() => document.body.scrollHeight)
for (let y = 0; y < H; y += 500) { await p.evaluate((y) => window.scrollTo(0, y), y); await p.waitForTimeout(90) }
// learning path step -> opens vendor/launch checklist tab
await p.getByRole('tab', { name: 'Launching a website' }).click()
await p.locator('#path-panel a', { hasText: 'Website launch checklist' }).click()
await p.waitForTimeout(1200)
console.log('active tab:', await p.locator('#checklists [role=tab][aria-selected=true]').innerText())
console.log('checklists top px:', Math.round(await p.evaluate(() => document.getElementById('checklists').getBoundingClientRect().top)))
// tick 3 items, switch tabs, persistence of counts
const boxes = p.locator('#checklist-panel input[type=checkbox]')
await boxes.nth(0).check({ force: true }); await boxes.nth(1).check({ force: true }); await boxes.nth(2).check({ force: true })
await p.getByRole('tab', { name: /Choosing a software partner/ }).click()
await p.getByRole('tab', { name: /Website launch checklist/ }).click()
console.log('launch ticks kept:', await p.locator('#checklist-panel input:checked').count())
await p.locator('#checklists').screenshot({ path: `${sp}/res-checklists.png` })
console.log('product grid present:', await p.locator('text=Using our products').count(), '| "Quickest way in":', await p.locator('text=Quickest way in').count())
await p.locator('#use').screenshot({ path: `${sp}/res-use2.png` })
const m = await b.newPage({ viewport: { width: 390, height: 844 } })
await m.goto('http://localhost:4173/resources', { waitUntil: 'networkidle' })
await m.addStyleTag({ content: 'html{scroll-behavior:auto!important}' })
await m.waitForTimeout(3500)
await m.getByText('Reject optional').first().click().catch(() => {})
await m.locator('#checklists').scrollIntoViewIfNeeded(); await m.waitForTimeout(700)
await m.locator('#checklists').screenshot({ path: `${sp}/res-checklists-m.png` })
console.log('mobile overflow:', await m.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), 'errors:', errs)
await b.close()
